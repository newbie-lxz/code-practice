#include <iostream>
#include <vector>
#include <algorithm>

using namespace std;

typedef long long ll;
typedef __int128 i128;

/*
    题目中：

    k >= 11
    所有 ai 和 v <= 1e12

    当 k 最小时 k = 11：

    11^11 < 1e12
    11^12 > 1e12

    所以最多只需要 12 个 k 进制位。
*/
const int MAXD = 12;

/*
    线段树中的每个节点维护：

    sum[j]:
        当前区间所有 ai 的第 j 个 k 进制位之和 mod k

    fs[j]:
        当前区间所有 f(ai) 的第 j 个 k 进制位之和 mod k

        注意：
        题目查询是

        f(a_l) ⊕k f(a_{l+1}) ⊕k ... ⊕k f(a_r)

        而 ⊕k 本质就是每一位分别求和 mod k，
        所以维护 fs[j] 即可。

    lazy:
        这个区间还没有向下传递的 ⊕k 修改。

        本来可以存一个 lazy[MAXD]，
        但这样线段树非常占内存。

        因此这里把 lazy 重新编码成一个普通整数。
*/
struct Node
{
    int sum[MAXD] = {};
    int fs[MAXD] = {};

    ll lazy = 0;
};


/*
    全局变量
*/
int n, m;
ll k;

/*
    实际需要多少个 k 进制位。

    虽然 MAXD = 12，
    但是比如 k = 1000000000 时实际上只有 2 位，
    所以只处理 DIG 位可以减少很多计算。
*/
int DIG;

/*
    线段树。

    我们会把底层叶子数量扩充为 2 的幂 S，
    然后只开 2*S 个节点。

    n <= 5e5

    S 最大是 524288，
    所以节点总数约 1048576。

    比直接 tree[4*n] 更节省内存。
*/
int S;
vector<Node> tree;


/*
===============================================================
                      工具函数
===============================================================
*/


/*
    求：

        a ⊕k b

    即把 a、b 写成 k 进制，
    每一位相加 mod k。

    例如 k = 3：

        11 = (102)_3
         7 = (021)_3

    则：

        102
      ⊕ 021
      -----
        120

    返回对应的十进制数。
*/
ll xor_k(ll a, ll b)
{
    i128 res = 0;
    i128 base = 1;

    for(int i = 0; i < DIG; i++)
    {
        ll da = a % k;
        ll db = b % k;

        ll d = (da + db) % k;

        res += (i128)d * base;

        a /= k;
        b /= k;

        base *= k;
    }

    return (ll)res;
}


/*
    将一个数 x 拆成 k 进制。

    digit[0]：最低位
    digit[1]：k^1 位
    digit[2]：k^2 位
    ...
*/
void get_digits(ll x, int digit[])
{
    for(int i = 0; i < DIG; i++)
    {
        digit[i] = x % k;
        x /= k;
    }
}


/*
===============================================================
                  f(n) 的核心数学性质
===============================================================

    假设：

        n = d0*k^0 + d1*k^1 + d2*k^2 + ...

    其中：

        d0 为最低位

    可以证明：

    1. f(n) 的第 0 位：

             d0(d0+1)
        ---------------- mod k
                2

    2. 对 j >= 1：

        f(n) 的第 j 位：

        dj * (d0 + 1) mod k


    因此 f(n) 不需要从：

        f(1), f(2), ..., f(n)

    一个个算。

    直接看 n 的 k 进制各位即可。
*/


/*
===============================================================
                     初始化叶子节点
===============================================================
*/


/*
    将单个 ai 初始化到一个线段树叶子中。
*/
void init_leaf(Node &node, ll x)
{
    int d[MAXD] = {};

    get_digits(x, d);

    /*
        一个叶子只有一个数字，
        所以 sum[j] 就等于数字本身的第 j 位。
    */
    for(int j = 0; j < DIG; j++)
    {
        node.sum[j] = d[j];
    }

    /*
        f(x) 的最低位：

            d0(d0+1)/2 mod k

        用 __int128 防止乘法溢出。
    */
    node.fs[0] =
        (ll)((i128)d[0] * (d[0] + 1) / 2 % k);

    /*
        高位：

            fj = dj * (d0+1) mod k
    */
    for(int j = 1; j < DIG; j++)
    {
        node.fs[j] =
            (ll)((i128)d[j] * (d[0] + 1) % k);
    }
}


/*
===============================================================
                     合并两个子节点
===============================================================
*/


/*
    父节点的信息就是左右儿子对应位相加 mod k。
*/
void pull(int p)
{
    for(int j = 0; j < DIG; j++)
    {
        tree[p].sum[j] =
            (tree[p * 2].sum[j]
             + tree[p * 2 + 1].sum[j]) % k;

        tree[p].fs[j] =
            (tree[p * 2].fs[j]
             + tree[p * 2 + 1].fs[j]) % k;
    }
}


/*
===============================================================
                对整个节点执行一次 ⊕k v
===============================================================
*/


/*
    当前节点代表一个长度为 len 的区间。

    我们要对其中每一个 ai：

        ai = ai ⊕k v

    但不能真的遍历每一个 ai。

    所以利用公式一次性修改整个节点的信息。
*/
void apply(int p, ll v, int len)
{
    int c[MAXD] = {};

    get_digits(v, c);

    /*
        v 的最低位记作 c0。

        原区间所有数字最低位之和：

            S0 = sum[0]
    */
    ll oldS0 = tree[p].sum[0];

    ll c0 = c[0];


    /*
    ===========================================================
                 更新 fs[0]
    ===========================================================

        对单个数字，最低位原本为 x：

            f0(x) = x(x+1)/2

        修改后：

            x -> x + c0   (mod k)

        因为 k 为奇数，可以得到：

            f0(x+c0)
            =
            f0(x)
            + c0*x
            + c0(c0+1)/2        (mod k)

        整个区间求和：

            F0'
            =
            F0
            + c0 * Σx
            + len * c0(c0+1)/2

        即：

            F0'
            =
            F0
            + c0*S0
            + len*c0(c0+1)/2
    */

    i128 add0 = 0;

    add0 += (i128)c0 * oldS0;

    add0 +=
        (i128)len
        * c0
        * (c0 + 1)
        / 2;

    tree[p].fs[0] =
        (tree[p].fs[0] + add0) % k;


    /*
    ===========================================================
                更新 fs[j]，j >= 1
    ===========================================================

        对某一个高位：

            x = d0
            y = dj

        原：

            fj = y(x+1)

        修改：

            x -> x+c0
            y -> y+cj

        所以：

            fj'
            =
            (y+cj)(x+c0+1)

        展开：

            =
            y(x+1)
            + c0*y
            + cj*(x+1)
            + c0*cj

        对整个区间求和：

            Fj'
            =
            Fj
            + c0*Sj
            + cj*(S0 + len)
            + len*c0*cj
    */

    for(int j = 1; j < DIG; j++)
    {
        ll cj = c[j];

        i128 add = 0;

        /*
            c0 * Sj
        */
        add +=
            (i128)c0
            * tree[p].sum[j];

        /*
            cj * (S0 + len)
        */
        add +=
            (i128)cj
            * (oldS0 + len);

        /*
            len * c0 * cj
        */
        add +=
            (i128)len
            * c0
            * cj;

        tree[p].fs[j] =
            (tree[p].fs[j] + add) % k;
    }


    /*
    ===========================================================
                       更新 sum[j]
    ===========================================================

        第 j 位：

            dj -> dj + cj mod k

        所以整个区间：

            Sj'
            =
            Sj + len*cj mod k
    */

    for(int j = 0; j < DIG; j++)
    {
        tree[p].sum[j] =
            (tree[p].sum[j]
             + (i128)len * c[j]) % k;
    }


    /*
    ===========================================================
                         更新 lazy
    ===========================================================

        如果之前已经有：

            lazy = x

        现在又进行一次：

            ⊕k v

        那么总效果就是：

            x ⊕k v
    */

    tree[p].lazy =
        xor_k(tree[p].lazy, v);
}


/*
===============================================================
                      下传懒标记
===============================================================
*/


void push(int p, int l, int r)
{
    /*
        没有懒标记，不处理。
    */
    if(tree[p].lazy == 0)
        return;

    /*
        已经是叶子也无需再往下传。
    */
    if(l == r)
    {
        tree[p].lazy = 0;
        return;
    }

    int mid = (l + r) / 2;

    /*
        左儿子长度：
            mid-l+1

        右儿子长度：
            r-mid
    */

    apply(
        p * 2,
        tree[p].lazy,
        mid - l + 1
    );

    apply(
        p * 2 + 1,
        tree[p].lazy,
        r - mid
    );

    /*
        已经传给两个孩子，
        当前节点懒标记清空。
    */
    tree[p].lazy = 0;
}


/*
===============================================================
                    区间修改
===============================================================
*/


/*
    把 [ql, qr] 中所有 ai：

        ai = ai ⊕k v
*/
void update(
    int p,
    int l,
    int r,
    int ql,
    int qr,
    ll v
)
{
    /*
        当前区间：

            [l,r]

        完全包含于：

            [ql,qr]

        直接整体修改。
    */
    if(ql <= l && r <= qr)
    {
        apply(
            p,
            v,
            r - l + 1
        );

        return;
    }

    /*
        当前节点要继续往下访问，
        必须先把以前的 lazy 下传。
    */
    push(p, l, r);

    int mid = (l + r) / 2;

    if(ql <= mid)
    {
        update(
            p * 2,
            l,
            mid,
            ql,
            qr,
            v
        );
    }

    if(qr > mid)
    {
        update(
            p * 2 + 1,
            mid + 1,
            r,
            ql,
            qr,
            v
        );
    }

    /*
        两个儿子变化后重新计算当前节点。
    */
    pull(p);
}


/*
===============================================================
                       区间查询
===============================================================
*/


/*
    查询：

        f(a_l)
        ⊕k
        f(a_{l+1})
        ⊕k
        ...
        ⊕k
        f(a_r)

    ans[j] 表示最终答案的第 j 个 k 进制位。
*/
void query(
    int p,
    int l,
    int r,
    int ql,
    int qr,
    int ans[]
)
{
    /*
        当前节点完整落入查询区间。
    */
    if(ql <= l && r <= qr)
    {
        for(int j = 0; j < DIG; j++)
        {
            ans[j] += tree[p].fs[j];

            ans[j] %= k;
        }

        return;
    }

    /*
        访问儿子前先下传懒标记。
    */
    push(p, l, r);

    int mid = (l + r) / 2;

    if(ql <= mid)
    {
        query(
            p * 2,
            l,
            mid,
            ql,
            qr,
            ans
        );
    }

    if(qr > mid)
    {
        query(
            p * 2 + 1,
            mid + 1,
            r,
            ql,
            qr,
            ans
        );
    }
}


/*
===============================================================
                  k 进制答案转十进制
===============================================================
*/


/*
    ans[]：

        ans[0] * k^0
      + ans[1] * k^1
      + ans[2] * k^2
      + ...

    用秦九韶方式转换：

        (((最高位)*k + 下一位)*k + ...)
*/
i128 digits_to_number(int ans[])
{
    i128 res = 0;

    for(int i = DIG - 1; i >= 0; i--)
    {
        res *= k;
        res += ans[i];
    }

    return res;
}


/*
    输出 __int128。
*/
void print_i128(i128 x)
{
    if(x == 0)
    {
        cout << 0 << '\n';
        return;
    }

    string s;

    while(x > 0)
    {
        int digit = x % 10;

        s.push_back('0' + digit);

        x /= 10;
    }

    reverse(s.begin(), s.end());

    cout << s << '\n';
}


/*
===============================================================
                           main
===============================================================
*/


int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n >> m >> k;


    /*
    ===========================================================
                计算实际需要的 k 进制位数 DIG
    ===========================================================

        所有 ai 和 v <= 1e12。

        找最小 DIG，使得：

            k^DIG > 1e12
    */

    DIG = 1;

    i128 power = k;

    while(power <= (i128)1000000000000LL)
    {
        DIG++;

        power *= k;
    }


    /*
        理论上一定 <= 12。
    */
    if(DIG > MAXD)
        DIG = MAXD;


    /*
    ===========================================================
                计算线段树叶子数量 S
    ===========================================================
    */

    S = 1;

    while(S < n)
        S <<= 1;


    /*
        线段树节点：

            1
           / \
          2   3
         ...

        最底层叶子从 tree[S] 开始。
    */
    tree.resize(S * 2);


    /*
    ===========================================================
                     读入初始序列
    ===========================================================
    */

    for(int i = 1; i <= n; i++)
    {
        ll x;

        cin >> x;

        /*
            第 i 个元素对应：

                tree[S + i - 1]
        */
        init_leaf(
            tree[S + i - 1],
            x
        );
    }


    /*
        n 后面一直到 S 的叶子都保持为 0。

        因为实际操作范围始终 <= n，
        所以这些额外叶子不会影响答案。
    */


    /*
    ===========================================================
                   自底向上构造线段树
    ===========================================================
    */

    for(int p = S - 1; p >= 1; p--)
    {
        pull(p);
    }


    /*
    ===========================================================
                       处理 m 次操作
    ===========================================================
    */

    while(m--)
    {
        int type;

        cin >> type;


        /*
        =======================================================
                         操作一

            1 l r v

            将：

                a_i = a_i ⊕k v

            对所有 i ∈ [l,r]
        =======================================================
        */

        if(type == 1)
        {
            int l, r;
            ll v;

            cin >> l >> r >> v;

            update(
                1,
                1,
                S,
                l,
                r,
                v
            );
        }


        /*
        =======================================================
                         操作二

            2 l r

            求：

                f(a_l)
                ⊕k
                f(a_{l+1})
                ⊕k
                ...
                ⊕k
                f(a_r)
        =======================================================
        */

        else
        {
            int l, r;

            cin >> l >> r;

            int ans[MAXD] = {};

            query(
                1,
                1,
                S,
                l,
                r,
                ans
            );


            /*
                将 k 进制答案转换成普通十进制。
            */
            i128 result =
                digits_to_number(ans);


            print_i128(result);
        }
    }

    return 0;
}